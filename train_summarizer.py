from torch.utils.data import DataLoader, Dataset
from transformers import BartForConditionalGeneration, BartTokenizer
import torch

# Step 1: Define Custom Dataset
class SummaryDataset(Dataset):
    def __init__(self, inputs, labels):
        self.inputs = inputs
        self.labels = labels

    def __len__(self):
        return len(self.inputs['input_ids'])

    def __getitem__(self, idx):
        return {
            'input_ids': self.inputs['input_ids'][idx],
            'attention_mask': self.inputs['attention_mask'][idx],
            'labels': self.labels['input_ids'][idx],
        }

# Step 2: Tokenize Input and Labels
train_encodings = tokenizer(
    list(train_data['InputText']), truncation=True, padding=True, max_length=256, return_tensors="pt"
)
train_labels = tokenizer(
    list(train_data['Summary']), truncation=True, padding=True, max_length=256, return_tensors="pt"
)

# Step 3: Create Dataset and DataLoader
dataset = SummaryDataset(train_encodings, train_labels)
batch_size = 16  # Adjusted batch size for T4 GPU
dataloader = DataLoader(dataset, batch_size=batch_size, shuffle=True)

# Step 4: Optimizer and Mixed Precision Training Setup
optimizer = torch.optim.AdamW(model.parameters(), lr=5e-5)

epochs = 3
gradient_accumulation_steps = 4  # Adjust gradient accumulation to balance memory and performance

from torch.cuda.amp import GradScaler, autocast  # Enable mixed precision training
scaler = GradScaler()

# Step 5: Move Model to GPU
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
model.to(device)

# Step 6: Training Loop
print(f"Training on {device}...")

for epoch in range(epochs):
    model.train()
    epoch_loss = 0
    for step, batch in enumerate(dataloader):
        # Move batch to GPU
        input_ids = batch['input_ids'].to(device)
        attention_mask = batch['attention_mask'].to(device)
        labels = batch['labels'].to(device)

        # Forward pass with mixed precision
        with autocast():
            outputs = model(input_ids, attention_mask=attention_mask, labels=labels)
            loss = outputs.loss / gradient_accumulation_steps  # Normalize loss for gradient accumulation

        # Backward pass with mixed precision
        scaler.scale(loss).backward()

        # Gradient accumulation step
        if (step + 1) % gradient_accumulation_steps == 0 or (step + 1) == len(dataloader):
            scaler.step(optimizer)  # Update weights
            scaler.update()  # Update scaler
            optimizer.zero_grad()  # Clear gradients

        epoch_loss += loss.item() * gradient_accumulation_steps

        # Print loss every 10 steps
        if step % 10 == 0:
            print(f"Epoch {epoch + 1}, Step {step + 1}/{len(dataloader)}, Loss: {loss.item():.4f}")

    print(f"Epoch {epoch + 1} completed. Average Loss: {epoch_loss / len(dataloader):.4f}")

print("Training complete.")

